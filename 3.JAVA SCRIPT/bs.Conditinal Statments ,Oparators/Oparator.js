let age=5;
let grace=2;

// Arithmatic Oparator
console.log(age+grace);
console.log(age-grace);
console.log(age*grace);
console.log(age/grace);
console.log(age**grace);
console.log(age%grace);

//increament/decrement
console.log(+age);
console.log(-age);
console.log(++age);
console.log(age++);
console.log(--age);
console.log(age--);

// Assigment Oparator
let num=10;
